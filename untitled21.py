import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_log_error
import lightgbm as lgb

# 1. Load data
train = pd.read_csv("train.csv")
test = pd.read_csv("test.csv")
meal = pd.read_csv("meal_info.csv")
center = pd.read_csv("fulfilment_center_info.csv")
sample_submission = pd.read_csv("sample_submission.csv")
sample_submission.head()


# 2. Merge extra info
train = train.merge(meal, on="meal_id", how="left")
test = test.merge(meal, on="meal_id", how="left")

train = train.merge(center, on="center_id", how="left")
test = test.merge(center, on="center_id", how="left")

# 3. Basic cleaning / missing values
train.fillna(0, inplace=True)
test.fillna(0, inplace=True)

# 4. Transform target
train["log_num_orders"] = np.log1p(train["num_orders"])

# 5. Feature engineering function
def create_features(df):
    # Discount / price features
    df["discount"] = df["base_price"] - df["checkout_price"]
    df["discount_pct"] = df["discount"] / (df["base_price"] + 1e-9)

    # Encode categorical features to numeric codes
    df["category_code"] = df["category"].astype("category").cat.codes
    df["cuisine_code"] = df["cuisine"].astype("category").cat.codes
    df["center_type_code"] = df["center_type"].astype("category").cat.codes
    df["region_code2"] = df["region_code"].astype("category").cat.codes
    df["city_code2"] = df["city_code"].astype("category").cat.codes

    # Interaction / combined feature
    df["center_meal_interaction"] = df["center_id"].astype(str) + "_" + df["meal_id"].astype(str)
    df["center_meal_int_code"] = df["center_meal_interaction"].astype("category").cat.codes

    return df

train = create_features(train)
test = create_features(test)

# 6. Define features (exclude identifiers & target)
feature_cols = [
    "week",
    "checkout_price", "base_price",
    "discount", "discount_pct",
    "emailer_for_promotion", "homepage_featured",
    "category_code", "cuisine_code",
    "center_type_code", "region_code2", "city_code2",
    "center_id", "meal_id", "center_meal_int_code"
]

X = train[feature_cols]
y = train["log_num_orders"]

# 7. Train / validation split
X_train, X_val, y_train, y_val = train_test_split(
    X, y, test_size=0.1, random_state=42
)

# 8. Model & training with callbacks
model = lgb.LGBMRegressor(
    n_estimators=1000,
    learning_rate=0.05,
    max_depth=8,
    subsample=0.8,
    colsample_bytree=0.8,
    random_state=42
)

model.fit(
    X_train,
    y_train,
    eval_set=[(X_val, y_val)],
    callbacks=[lgb.early_stopping(stopping_rounds=50)]
)

# 9. Validate
y_val_pred = model.predict(X_val)
y_val_true = np.expm1(y_val)
y_val_pred_inv = np.expm1(y_val_pred)

rmsle = np.sqrt(mean_squared_log_error(y_val_true, y_val_pred_inv))
print("Validation RMSLE:", rmsle)

# 10. Predict on test & prepare submission
X_test = test[feature_cols]
y_test_pred = model.predict(X_test)
test["num_orders"] = np.expm1(y_test_pred)

# Assuming sample_submission has “id” column to join
submission = pd.read_csv("sample_submission.csv")

submission.to_csv("submission_full.csv", index=False)

print()